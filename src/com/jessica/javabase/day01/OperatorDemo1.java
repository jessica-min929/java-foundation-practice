package com.jessica.javabase.day01;

public class OperatorDemo1 {
    public static void main(String[] args) {
        //整数的加减乘除取余运算
        int a =10;
        int b =2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
        System.out.println("------------------------------------------------------------");

        //小数的加减乘除取余运算
        double c = 12.0;
        double d = 2.0;
        System.out.println(c+d);
        System.out.println(c-d);
        System.out.println(c*d);
        System.out.println(c/d);
        System.out.println(c%d);
    }


}
